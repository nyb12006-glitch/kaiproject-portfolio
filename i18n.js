let currentDict=translations.es;

// Devuelve el texto traducido de una clave (lo usa script.js para textos dinámicos)
function t(key){return currentDict[key]!==undefined?currentDict[key]:(translations.es[key]||"");}

function detectInitialLang(){
 try{
  const saved=localStorage.getItem(LANG_STORAGE_KEY);
  if(saved&&SUPPORTED_LANGS.includes(saved))return saved;
 }catch(e){}
 const browserLang=(navigator.language||"es").slice(0,2).toLowerCase();
 return SUPPORTED_LANGS.includes(browserLang)?browserLang:"es";
}

function applyLanguage(lang){
 const dict=translations[lang]||translations.es;
 currentDict=dict;
 document.documentElement.lang=lang;

 document.querySelectorAll("[data-i18n]").forEach(el=>{
  const value=dict[el.dataset.i18n];
  if(value!==undefined)el.textContent=value;
 });

 document.querySelectorAll("[data-i18n-aria]").forEach(el=>{
  const value=dict[el.dataset.i18nAria];
  if(value!==undefined)el.setAttribute("aria-label",value);
 });

 if(dict["meta.title"])document.title=dict["meta.title"];
 const metaDescription=document.getElementById("metaDescription");
 if(metaDescription&&dict["meta.description"])metaDescription.setAttribute("content",dict["meta.description"]);
 const ogTitle=document.getElementById("ogTitle");
 if(ogTitle&&dict["meta.title"])ogTitle.setAttribute("content",dict["meta.title"]);
 const ogDescription=document.getElementById("ogDescription");
 if(ogDescription&&dict["meta.ogDescription"])ogDescription.setAttribute("content",dict["meta.ogDescription"]);
 const twitterTitle=document.getElementById("twitterTitle");
 if(twitterTitle&&dict["meta.title"])twitterTitle.setAttribute("content",dict["meta.title"]);
 const twitterDescription=document.getElementById("twitterDescription");
 if(twitterDescription&&dict["meta.ogDescription"])twitterDescription.setAttribute("content",dict["meta.ogDescription"]);

 const langSwitch=document.getElementById("langSwitch");
 if(langSwitch)langSwitch.value=lang;

 try{localStorage.setItem(LANG_STORAGE_KEY,lang);}catch(e){}
 document.dispatchEvent(new CustomEvent("langchange",{detail:{lang}}));
}

applyLanguage(detectInitialLang());

const langSwitchEl=document.getElementById("langSwitch");
if(langSwitchEl){
 langSwitchEl.addEventListener("change",e=>applyLanguage(e.target.value));
}
